    def _combine_signals(self, signals: List[MLSignal]) -> EnsembleSignal:
        """Combine multiple signals into ensemble prediction"""
        
        # Weight signals by confidence and model accuracy
        call_score = 0
        put_score = 0
        hold_score = 0
        
        for signal in signals:
            weight = signal.confidence / 100
            
            if signal.direction == TradingDirection.CALL:
                call_score += weight
            elif signal.direction == TradingDirection.PUT:
                put_score += weight
            else:
                hold_score += weight
        
        total_score = call_score + put_score + hold_score
        
        # Determine final direction
        if call_score > put_score and call_score > hold_score:
            final_direction = TradingDirection.CALL
            final_confidence = (call_score / total_score) * 100 if total_score > 0 else 50
        elif put_score > call_score and put_score > hold_score:
            final_direction = TradingDirection.PUT
            final_confidence = (put_score / total_score) * 100 if total_score > 0 else 50
        else:
            final_direction = TradingDirection.HOLD
            final_confidence = 30
        
        # Calculate consensus
        direction_counts = {
            TradingDirection.CALL: sum(1 for s in signals if s.direction == TradingDirection.CALL),
            TradingDirection.PUT: sum(1 for s in signals if s.direction == TradingDirection.PUT),
            TradingDirection.HOLD: sum(1 for s in signals if s.direction == TradingDirection.HOLD)
        }
        max_agreement = max(direction_counts.values())
        consensus_score = max_agreement / len(signals) if signals else 0
        
        # Determine risk level
        if final_confidence > 75 and consensus_score > 0.7:
            risk_level = "LOW"
        elif final_confidence > 60 and consensus_score > 0.5:
            risk_level = "MEDIUM"
        else:
            risk_level = "HIGH"
        
        # Recommended expiry based on regime
        if self.current_regime in [MarketRegime.TRENDING_UP, MarketRegime.TRENDING_DOWN]:
            recommended_expiry = "1m-5m"
        elif self.current_regime == MarketRegime.VOLATILE:
            recommended_expiry = "30s-1m"
        else:
            recommended_expiry = "1m-3m"
        
        return EnsembleSignal(
            final_direction=final_direction,
            final_confidence=final_confidence,
            consensus_score=consensus_score,
            individual_signals=signals,
            market_regime=self.current_regime,
            risk_level=risk_level,
            recommended_expiry=recommended_expiry
        )
    
    async def record_trade_result(self, signal_id: str, outcome: str) -> Dict[str, Any]:
        """
        Record trade result for continuous learning.
        
        Args:
            signal_id: ID of the original signal
            outcome: "WIN" or "LOSS"
        
        Returns:
            Updated statistics
        """
        try:
            self.total_trades += 1
            if outcome.upper() == "WIN":
                self.winning_trades += 1
            
            self.trade_results.append({
                "signal_id": signal_id,
                "outcome": outcome,
                "timestamp": datetime.now(timezone.utc).isoformat()
            })
            
            win_rate = (self.winning_trades / self.total_trades) * 100 if self.total_trades > 0 else 0
            
            # Trigger retraining if enough new data
            retrain_needed = len(self.trade_results) >= 100 and len(self.trade_results) % 50 == 0
            
            return {
                "success": True,
                "total_trades": self.total_trades,
                "winning_trades": self.winning_trades,
                "win_rate": win_rate,
                "retrain_suggested": retrain_needed
            }
            
        except Exception as e:
            logger.error(f"Error recording trade result: {e}")
            return {"success": False, "error": str(e)}
    
