class EnhancedAITradingSystem:
    """
    Main AI Trading System that combines all models.
    Provides ensemble predictions and continuous learning.
    """
    
    def __init__(self):
        self.trend_model = TrendFollowingModel()
        self.mean_reversion_model = MeanReversionModel()
        self.pattern_model = PatternRecognitionModel()
        
        # Training data storage
        self.training_data = deque(maxlen=10000)
        self.trade_results = deque(maxlen=1000)
        
        # Model states
        self.models_trained = False
        self.last_training_time = None
        self.total_trades = 0
        self.winning_trades = 0
        
        # Market regime detection
        self.current_regime = MarketRegime.CALM
        
        logger.info("EnhancedAITradingSystem initialized")
    
    def detect_market_regime(self, features: np.ndarray, feature_names: List[str]) -> MarketRegime:
        """Detect current market regime"""
        try:
            vol_idx = feature_names.index("volatility_20") if "volatility_20" in feature_names else -1
            trend_idx = feature_names.index("trend_strength") if "trend_strength" in feature_names else -1
            
            volatility = features[vol_idx] if vol_idx >= 0 else 0.01
            trend = features[trend_idx] if trend_idx >= 0 else 0
            
            # Classify regime
            if volatility > 0.02:  # High volatility
                return MarketRegime.VOLATILE
            elif abs(trend) > 50:
                return MarketRegime.TRENDING_UP if trend > 0 else MarketRegime.TRENDING_DOWN
            elif abs(trend) < 10:
                return MarketRegime.RANGING
            else:
                return MarketRegime.CALM
                
        except Exception as e:
            logger.error(f"Error detecting market regime: {e}")
            return MarketRegime.CALM
    
    def prepare_training_labels(self, closes: np.ndarray, lookahead: int = 5) -> np.ndarray:
        """
        Create training labels based on future price movement.
        
        Args:
            closes: Array of closing prices
            lookahead: Number of periods to look ahead
        
        Returns:
            Array of labels: 1 (up), -1 (down), 0 (neutral)
        """
        labels = np.zeros(len(closes))
        
        for i in range(len(closes) - lookahead):
            future_return = (closes[i + lookahead] - closes[i]) / closes[i]
            
            if future_return > 0.001:  # 0.1% threshold
                labels[i] = 1
            elif future_return < -0.001:
                labels[i] = -1
            else:
                labels[i] = 0
        
        return labels
    
    async def train_models(self, ohlcv_data: Dict[str, np.ndarray]) -> Dict[str, Any]:
        """
        Train all ML models with historical data.
        
        Args:
            ohlcv_data: Dict with 'open', 'high', 'low', 'close', 'volume'
        
        Returns:
            Training results summary
        """
        results = {
            "success": False,
            "models_trained": [],
            "accuracies": {},
            "training_samples": 0
        }
        
        try:
            # Create features
            features, feature_names = FeatureEngineering.create_features(ohlcv_data)
            if len(features) < 200:
                results["error"] = "Insufficient data for training"
                return results
            
            # Create labels
            closes = ohlcv_data.get('close', np.array([]))
            labels = self.prepare_training_labels(closes)
            
            # Align features and labels
            min_len = min(len(features), len(labels))
            features = features[:min_len]
            labels = labels[:min_len]
            
            # Remove samples with neutral labels for trend/mean reversion
            non_neutral_mask = labels != 0
            train_features = features[non_neutral_mask]
            train_labels = labels[non_neutral_mask]
            
            results["training_samples"] = len(train_features)
            
            # Train each model
            if self.trend_model.train(train_features, train_labels, feature_names):
                results["models_trained"].append("TrendFollowing")
                results["accuracies"]["TrendFollowing"] = self.trend_model.accuracy
            
            if self.mean_reversion_model.train(train_features, train_labels, feature_names):
                results["models_trained"].append("MeanReversion")
                results["accuracies"]["MeanReversion"] = self.mean_reversion_model.accuracy
            
            if self.pattern_model.train(features, labels, feature_names):
                results["models_trained"].append("PatternRecognition")
                results["accuracies"]["PatternRecognition"] = self.pattern_model.accuracy
            
            self.models_trained = len(results["models_trained"]) > 0
            self.last_training_time = datetime.now(timezone.utc)
            results["success"] = self.models_trained
            
            logger.info(f"Model training complete: {results}")
            return results
            
        except Exception as e:
            logger.error(f"Error during model training: {e}")
            results["error"] = str(e)
            return results
    
    async def generate_signal(self, ohlcv_data: Dict[str, np.ndarray], custom_strategy: Dict = None) -> Optional[EnsembleSignal]:
        """
        Generate ensemble trading signal from all models.
        
        Args:
            ohlcv_data: Current market OHLCV data
            custom_strategy: Optional custom strategy from Strategy Builder
        
        Returns:
            EnsembleSignal combining all model predictions
        """
        try:
            # Create features
            features, feature_names = FeatureEngineering.create_features(ohlcv_data)
            if len(features) < 10:
                return None
            
            # Get latest features
            latest_features = features[-1]
            
            # Detect market regime
            self.current_regime = self.detect_market_regime(latest_features, feature_names)
            
            # Collect signals from all models
            signals = []
            
            # Trend following signal
            if self.trend_model.is_trained:
                trend_signal = self.trend_model.predict(latest_features)
                if trend_signal:
                    signals.append(trend_signal)
            
            # Mean reversion signal
            if self.mean_reversion_model.is_trained:
                mr_signal = self.mean_reversion_model.predict(latest_features)
                if mr_signal:
                    signals.append(mr_signal)
            
            # Pattern recognition signal
            if self.pattern_model.is_trained:
                pattern_signal = self.pattern_model.predict(latest_features)
                if pattern_signal:
                    signals.append(pattern_signal)
            
            # Apply custom strategy if provided
            if custom_strategy:
                custom_signal = self._evaluate_custom_strategy(custom_strategy, ohlcv_data, latest_features, feature_names)
                if custom_signal:
                    signals.append(custom_signal)
            
            if not signals:
                return None
            
            # Combine signals using weighted voting
            return self._combine_signals(signals)
            
        except Exception as e:
            logger.error(f"Error generating signal: {e}")
            return None
    
    def _evaluate_custom_strategy(
        self, 
        strategy: Dict, 
        ohlcv_data: Dict[str, np.ndarray],
        features: np.ndarray,
        feature_names: List[str]
    ) -> Optional[MLSignal]:
        """
        Evaluate a custom strategy from the Strategy Builder.
        
        The strategy contains conditions like:
        {
            "name": "My RSI Strategy",
            "conditions": [
                {"indicator": "RSI", "condition": "crosses_below", "value": 30, "signal": "CALL"},
                {"indicator": "RSI", "condition": "crosses_above", "value": 70, "signal": "PUT"}
            ]
        }
        """
