@dataclass
class MLSignal:
    """Signal generated by ML model"""
    direction: TradingDirection
    confidence: float  # 0-100
    strategy_type: StrategyType
    model_name: str
    reasoning: str
    features_used: List[str] = field(default_factory=list)
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    
    def to_dict(self) -> Dict:
        return {
            "direction": self.direction.value,
            "confidence": self.confidence,
            "strategy_type": self.strategy_type.value,
            "model_name": self.model_name,
            "reasoning": self.reasoning,
            "features_used": self.features_used,
            "timestamp": self.timestamp.isoformat()
        }


@dataclass
class EnsembleSignal:
    """Combined signal from multiple ML models"""
    final_direction: TradingDirection
    final_confidence: float
    consensus_score: float  # How much models agree (0-1)
    individual_signals: List[MLSignal]
    market_regime: MarketRegime
    risk_level: str  # LOW, MEDIUM, HIGH
    recommended_expiry: str  # Suggested expiration time
    
    def to_dict(self) -> Dict:
        return {
            "final_direction": self.final_direction.value,
            "final_confidence": self.final_confidence,
            "consensus_score": self.consensus_score,
            "individual_signals": [s.to_dict() for s in self.individual_signals],
            "market_regime": self.market_regime.value,
            "risk_level": self.risk_level,
            "recommended_expiry": self.recommended_expiry
        }


class FeatureEngineering:
    """
    Feature engineering for ML models.
    Creates comprehensive feature sets for trading prediction.
    """
    
    @staticmethod
    def calculate_returns(prices: np.ndarray, periods: List[int] = [1, 5, 10, 20]) -> Dict[str, np.ndarray]:
        """Calculate returns over various periods"""
        returns = {}
        for period in periods:
            if len(prices) > period:
                returns[f"return_{period}"] = (prices[period:] - prices[:-period]) / prices[:-period]
        return returns
    
    @staticmethod
    def calculate_volatility(prices: np.ndarray, window: int = 20) -> np.ndarray:
        """Calculate rolling volatility"""
        returns = np.diff(prices) / prices[:-1]
        volatility = pd.Series(returns).rolling(window).std().values
        return volatility
    
    @staticmethod
    def calculate_momentum(prices: np.ndarray, period: int = 14) -> np.ndarray:
        """Calculate momentum indicator"""
        if len(prices) < period:
            return np.zeros(len(prices))
        momentum = prices[period:] - prices[:-period]
        return np.concatenate([np.zeros(period), momentum])
    
    @staticmethod
    def calculate_rsi(prices: np.ndarray, period: int = 14) -> np.ndarray:
        """Calculate RSI"""
        delta = np.diff(prices)
        gain = np.where(delta > 0, delta, 0)
        loss = np.where(delta < 0, -delta, 0)
        
        avg_gain = pd.Series(gain).rolling(period).mean().values
        avg_loss = pd.Series(loss).rolling(period).mean().values
        
        rs = np.where(avg_loss != 0, avg_gain / avg_loss, 0)
        rsi = 100 - (100 / (1 + rs))
        return np.concatenate([[50], rsi])
    
    @staticmethod
    def calculate_bollinger_position(prices: np.ndarray, period: int = 20, std_mult: float = 2.0) -> np.ndarray:
        """Calculate position within Bollinger Bands (-1 to 1)"""
        sma = pd.Series(prices).rolling(period).mean().values
        std = pd.Series(prices).rolling(period).std().values
        
        upper = sma + std_mult * std
        lower = sma - std_mult * std
        
        # Position: -1 at lower band, 0 at middle, 1 at upper band
        band_width = upper - lower
        position = np.where(band_width != 0, 
                          2 * (prices - lower) / band_width - 1,
                          0)
        return position
    
    @staticmethod
    def calculate_trend_strength(prices: np.ndarray, short_period: int = 10, long_period: int = 30) -> np.ndarray:
        """Calculate trend strength (-100 to 100)"""
        short_ma = pd.Series(prices).rolling(short_period).mean().values
        long_ma = pd.Series(prices).rolling(long_period).mean().values
        
        # Trend strength based on MA divergence
        strength = np.where(long_ma != 0,
                          100 * (short_ma - long_ma) / long_ma,
                          0)
        return np.clip(strength, -100, 100)
    
    @staticmethod
    def create_features(ohlcv_data: Dict[str, np.ndarray]) -> Tuple[np.ndarray, List[str]]:
        """
        Create comprehensive feature set from OHLCV data.
        
        Args:
            ohlcv_data: Dict with 'open', 'high', 'low', 'close', 'volume'
        
        Returns:
            Tuple of (features array, feature names)
        """
        closes = ohlcv_data.get('close', np.array([]))
        highs = ohlcv_data.get('high', np.array([]))
        lows = ohlcv_data.get('low', np.array([]))
        volumes = ohlcv_data.get('volume', np.array([]))
        
        if len(closes) < 50:
            return np.array([]), []
        
        features = []
        feature_names = []
        
        # Price-based features
        returns = FeatureEngineering.calculate_returns(closes)
        for name, values in returns.items():
            padded = np.concatenate([np.zeros(len(closes) - len(values)), values])
            features.append(padded)
            feature_names.append(name)
        
        # Volatility
        volatility = FeatureEngineering.calculate_volatility(closes)
        features.append(np.concatenate([[0], volatility]))
        feature_names.append("volatility_20")
        
        # Momentum
        momentum = FeatureEngineering.calculate_momentum(closes)
        features.append(momentum)
        feature_names.append("momentum_14")
        
        # RSI
        rsi = FeatureEngineering.calculate_rsi(closes)
        features.append(rsi)
        feature_names.append("rsi_14")
        
        # Bollinger position
        bb_pos = FeatureEngineering.calculate_bollinger_position(closes)
        features.append(bb_pos)
        feature_names.append("bb_position")
        
        # Trend strength
        trend = FeatureEngineering.calculate_trend_strength(closes)
        features.append(trend)
        feature_names.append("trend_strength")
        
        # High-Low range
        hl_range = (highs - lows) / closes
        features.append(hl_range)
        feature_names.append("hl_range")
        
        # Close position in range
        close_pos = np.where(highs != lows,
                           (closes - lows) / (highs - lows),
                           0.5)
        features.append(close_pos)
        feature_names.append("close_position")
        
        # Volume features (if available)
        if len(volumes) == len(closes) and np.any(volumes > 0):
            vol_ma = pd.Series(volumes).rolling(20).mean().values
            vol_ratio = np.where(vol_ma != 0, volumes / vol_ma, 1)
            features.append(vol_ratio)
            feature_names.append("volume_ratio")
        
        # Stack features
        feature_array = np.column_stack(features)
        
        # Remove NaN rows
        valid_mask = ~np.isnan(feature_array).any(axis=1)
        feature_array = feature_array[valid_mask]
        
        return feature_array, feature_names


class TrendFollowingModel:
    """
    AI model for early trend detection.
    Uses gradient boosting to identify emerging trends before they become obvious.
    """
    
    def __init__(self):
        self.model = GradientBoostingClassifier(
            n_estimators=100,
            max_depth=5,
            learning_rate=0.1,
            random_state=42
        ) if SKLEARN_AVAILABLE else None
        self.scaler = StandardScaler() if SKLEARN_AVAILABLE else None
        self.is_trained = False
        self.feature_names = []
        self.accuracy = 0.0
    
    def train(self, features: np.ndarray, labels: np.ndarray, feature_names: List[str]):
        """Train the trend following model"""
        if not SKLEARN_AVAILABLE or len(features) < 100:
            return False
        
        try:
            # Scale features
            features_scaled = self.scaler.fit_transform(features)
            
            # Train with time series split
            tscv = TimeSeriesSplit(n_splits=5)
            accuracies = []
            
            for train_idx, val_idx in tscv.split(features_scaled):
                X_train, X_val = features_scaled[train_idx], features_scaled[val_idx]
                y_train, y_val = labels[train_idx], labels[val_idx]
                
                self.model.fit(X_train, y_train)
                predictions = self.model.predict(X_val)
                accuracies.append(accuracy_score(y_val, predictions))
            
            self.accuracy = np.mean(accuracies)
            self.feature_names = feature_names
            self.is_trained = True
            
            logger.info(f"TrendFollowingModel trained with accuracy: {self.accuracy:.2%}")
            return True
            
        except Exception as e:
            logger.error(f"Error training TrendFollowingModel: {e}")
            return False
    
    def predict(self, features: np.ndarray) -> Optional[MLSignal]:
        """Generate trend following signal"""
        if not self.is_trained or not SKLEARN_AVAILABLE:
            return None
        
        try:
            features_scaled = self.scaler.transform(features.reshape(1, -1))
            prediction = self.model.predict(features_scaled)[0]
            probabilities = self.model.predict_proba(features_scaled)[0]
            
            confidence = max(probabilities) * 100
            
            if prediction == 1:  # Uptrend
                direction = TradingDirection.CALL
                reasoning = "Strong uptrend detected - momentum and MA alignment bullish"
            elif prediction == -1:  # Downtrend
                direction = TradingDirection.PUT
                reasoning = "Strong downtrend detected - momentum and MA alignment bearish"
            else:
                direction = TradingDirection.HOLD
                reasoning = "No clear trend - staying neutral"
            
            return MLSignal(
                direction=direction,
                confidence=confidence,
                strategy_type=StrategyType.TREND_FOLLOWING,
                model_name="TrendFollowingModel",
                reasoning=reasoning,
                features_used=self.feature_names[:5]
            )
            
        except Exception as e:
            logger.error(f"TrendFollowingModel prediction error: {e}")
            return None


